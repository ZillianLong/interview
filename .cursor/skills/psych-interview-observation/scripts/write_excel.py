def main():
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Sheet1"

    ws["A1"] = "维度"
    ws["B1"] = "面试观察"

    for i, (dim, content) in enumerate(DIMENSIONS, start=2):
        ws.cell(row=i, column=1, value=dim)
        cell = ws.cell(row=i, column=2, value=content)
        cell.alignment = Alignment(wrap_text=True, vertical="top")

    ws.column_dimensions["A"].width = 14
    ws.column_dimensions["B"].width = 90

    for i, (dim, _) in enumerate(DIMENSIONS, start=2):
        ws.row_dimensions[i].height = 200

    wb.save(EXCEL_OUTPUT)

    with open(MARKDOWN_OUTPUT, "w", encoding="utf-8") as f:
        f.write("# 心理风险维度 · 面试观察\n\n")
        f.write("> 定稿参照：[用户终稿.md](用户终稿.md)\n\n")
        for dim, content in DIMENSIONS:
            f.write(f"## {dim}\n\n{content}\n\n")

    print(f"Saved {EXCEL_OUTPUT} and {MARKDOWN_OUTPUT} with {len(DIMENSIONS)} dimensions")


if __name__ == "__main__":
    main()
